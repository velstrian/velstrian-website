/* Text files (the .vtt captions) are hashed with line endings normalised, because
   git may check them out as CRLF or LF depending on the machine. Bytes otherwise. */
const sha256 = (file) => {
  let buf = fs.readFileSync(file);
  if (/\.(vtt|txt)$/i.test(file)) buf = Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
  return crypto.createHash('sha256').update(buf).digest('hex');
};

/** The app legal pages that move here (D462 point 3), by route. Accessibility
    is not in the list: this site already publishes its own statement, and the
    app keeps a statement for the app, which is a different product. */
export const LEGAL_PAGES = ['dpa', 'sub-processors', 'residency', 'retention', 'refund-policy'];

/** Paths that now live on THIS site. A link to anything else from a moved page
    is a page that stays in the app, so it becomes app:/<path>. */
const SITE_PATHS = new Set([
  ...LEGAL_PAGES.map((p) => `/${p}`),
  '/privacy',
  '/terms',
  '/cookies',
  '/security',
  '/accessibility',
  '/contact',
  '/pricing',
  '/help',
]);

const GENERATED_NOTE =
  'GENERATED by astro/scripts/generate-help-centre.mjs from crowagent-platform. Do not edit here: change the platform source and run the script (D462).';

function loadJiti() {
  const req = createRequire(path.join(WEB, 'package.json'));
  const { createJiti } = req('jiti');
  const tsconfig = JSON.parse(fs.readFileSync(path.join(WEB, 'tsconfig.json'), 'utf8'));
  const alias = {};
  for (const [key, targets] of Object.entries(tsconfig.compilerOptions.paths ?? {})) {
    alias[key.replace(/\/\*$/, '')] = path.resolve(WEB, targets[0].replace(/\/\*$/, ''));
  }
  return createJiti(pathToFileURL(path.join(WEB, 'generate-help-centre.ts')).href, {
    alias,
    interopDefault: true,
    jsx: { runtime: 'automatic', importSource: 'react' },
    fsCache: false,
    moduleCache: true,
  });
}

/**
 * The site's writing rule (RULE 0-S, the website charter): no en or em dash in
 * text a reader sees. Two platform articles write a numeric range with an en
 * dash ("0–5 scale", "08:00–18:00"). A range reads the same with
 * "to", so it is written that way here. Anything else with a dash fails the
 * generator, so a new one is fixed in the platform rather than hidden here.
 */
function siteStyle(html) {
  const out = html.replace(/(\d)–(\d)/g, '$1 to $2');
  if (/[–—]/.test(out)) {
    throw new Error('generate-help-centre: a help article carries an en or em dash that is not a numeric range. Fix the wording in crowagent-platform/web/lib/help-articles.ts.');
  }
  return out;
}

/** Removes the common leading indentation of a template literal block and
    trims it, so the JSON holds the article and not the source file's layout.
    Relative indentation (inside a pre) is kept. */
function dedent(html) {
  const lines = html.replace(/\r\n/g, '\n').split('\n');
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^[ \t]*/)[0].length);
  const cut = indents.length ? Math.min(...indents) : 0;
  return lines
    .map((l) => l.slice(cut))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function siteHref(href) {
  if (!href.startsWith('/') || href.startsWith('//')) return href;
  const [pathPart, rest = ''] = href.split(/(?=[?#])/);
  const clean = pathPart.replace(/\/$/, '') || '/';
  const onSite = SITE_PATHS.has(clean) || clean.startsWith('/help/');
  if (onSite) return `${clean}/${rest}`;
  return `app:${pathPart}${rest}`;
}

const decode = (s) =>
  s
    .replace(/&#x27;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>');

/** Static markup of one legal page, as a Markdown document body. */
function legalMarkdown(markup, route) {
  /* Two app classes carry MEANING, not looks, and are translated rather than
     dropped: `italic` marks a "being confirmed" cell on /sub-processors (the
     page explains the italics to the reader), and `sr-only` hides a table
     caption visually, which this site's `.visually-hidden` does. */
  let html = markup
    .replace(/<!-- -->/g, '')
    .replace(/<span class="[^"]*\bitalic\b[^"]*">([\s\S]*?)<\/span>/g, '<em>$1</em>')
    .replace(/\sclass="([^"]*)"/g, (_m, cls) => (/\bsr-only\b/.test(cls) ? ' class="visually-hidden"' : ''))
    .replace(/\s(data-testid|style|aria-describedby)="[^"]*"/g, '')
    /* TableShell's scrolling region, on this site's own scroll recipe. */
    .replace(/<div role="region"/g, '<div class="prose-scroll" role="region"')
    .replace(/href="([^"]*)"/g, (_m, href) => `href="${siteHref(decode(href))}"`);
  /* After the clean up, so a correction matches the markup this site serves. */
  html = applyCorrections(route, html);

  const h1 = html.match(/<h1>([\s\S]*?)<\/h1>/);
  const heading = h1 ? decode(h1[1].replace(/<[^>]+>/g, '')).trim() : '';
  html = html.replace(/<h1>[\s\S]*?<\/h1>/, '');

  /* Unwrap the outer wrappers the app layout needs and a document does not: a
     page that returns one <div> or <section> around everything. */
  html = html.replace(/^\s*<div>([\s\S]*)<\/div>\s*$/, '$1');

  /* One top level block per line, a blank line between, which is what makes
     each one a Markdown HTML block. Headings become Markdown headings, so the
     Legal layout's contents rail is generated from them. */
  const blocks = [];
  const depthSafe = html;
  /* Nested same name tags (a div in a div) would end a lazy match early, so
     walk the string and balance tags by name rather than trusting a regex. */
  let i = 0;
  while (i < depthSafe.length) {
    const open = depthSafe.slice(i).match(/^\s*<([a-z0-9]+)\b[^>]*>/);
    if (!open) {
      const next = depthSafe.indexOf('<', i + 1);
      const text = depthSafe.slice(i, next === -1 ? undefined : next).trim();
      if (text) blocks.push(`<p>${text}</p>`);
      if (next === -1) break;
      i = next;
      continue;
    }
    const tag = open[1];
    const start = i + open[0].length - open[0].trimStart().length;
    let depth = 0;
    let j = start;
    const tagRe = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'g');
    tagRe.lastIndex = start;
    let m;
    while ((m = tagRe.exec(depthSafe))) {
      depth += m[1] ? -1 : 1;
      if (depth === 0) {
        j = m.index + m[0].length;
        break;
      }
    }
    if (depth !== 0) throw new Error(`generate-help-centre: unbalanced <${tag}> in a legal page`);
    const block = depthSafe.slice(start, j);
    if (tag === 'h2' || tag === 'h3') {
      const text = decode(block.replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
      blocks.push(`${tag === 'h2' ? '##' : '###'} ${text}`);
    } else {
      blocks.push(block);
    }
    i = j;
  }
  return { heading, body: blocks.join('\n\n') };
}

/*
 * CORRECTIONS WAITING ON THE PLATFORM SOURCE (owner correction 2026-10-26).
 *
 * Upstash and Resend are NOT used. Resend left the code on 2026-05-24
 * (REQ-PLATFORM-F-1), Brevo is the only email transport. The last Upstash
 * readers moved to each environment's own Postgres on 2026-09-24 (D151, commit
 * 632cdcd1e, guard web/__tests__/infra/no-upstash-reader-anywhere.test.ts).
 * The app pages these files are generated from still name both, and the app
 * side lane owns that fix, so the website applies it here until it lands.
 *
 * EACH ENTRY EXPIRES BY ITSELF. `find` must still be in the platform's rendered
 * page. When the platform is corrected, `find` is gone and the generator FAILS,
 * naming the entry to delete, so this table can never outlive the defect or
 * quietly become a second copy of the legal text.
 */
const PENDING_PLATFORM_CORRECTIONS = [
  /* EMPTY, and that is the state to keep it in. The Upstash entries for
     /sub-processors and /residency and the Resend entry for /retention all
     expired on 2026-10-26, when the app lane corrected the platform pages, and
     this generator failed until each was deleted, as designed. */
];

/** Applies the corrections for one route, and fails on any that has expired. */
function applyCorrections(route, markup) {
  let html = markup;
  for (const c of PENDING_PLATFORM_CORRECTIONS.filter((x) => x.route === route)) {
    if (!c.find.test(html)) {
      throw new Error(
        `generate-help-centre: the platform page app/(legal)/${route} no longer holds the text a pending correction fixes (${c.why}). The platform is corrected: delete this entry from PENDING_PLATFORM_CORRECTIONS.`,
      );
    }
    html = html.replace(c.find, c.replace);
  }
  return html;
}

/*
 * NO SUB-PROCESSOR THE PLATFORM HAS RETIRED MAY BE NAMED AS CURRENT. Read from
 * the platform's own "no longer engaged" table on /sub-processors, then every
 * other legal page, generated or hand written, is searched for each retired
 * name outside that table. Cheap, inside the existing help centre gate.
 */
function retiredProcessors(subProcessorsBody) {
  const ended = subProcessorsBody.match(/<caption class="visually-hidden">Sub-processors no longer engaged<\/caption>[\s\S]*?<\/table>/);
  if (!ended) throw new Error('generate-help-centre: /sub-processors has no "no longer engaged" table to read retired processors from');
  return [...ended[0].matchAll(/<th scope="row">([^<]+)<\/th>/g)].map((m) => m[1].trim());
}

function retiredNameFindings(files) {
  const subBody = files[path.join(LEGAL_DIR, 'sub-processors.md')];
  const retired = retiredProcessors(subBody);
  const findings = [];
  const legalFiles = fs.readdirSync(LEGAL_DIR).filter((f) => f.endsWith('.md'));
  for (const f of legalFiles) {
    const full = path.join(LEGAL_DIR, f);
    let text = files[full] ?? fs.readFileSync(full, 'utf8');
    text = text.replace(/<!--[\s\S]*?-->/g, '');
    if (f === 'sub-processors.md') {
      text = text.replace(/<caption class="visually-hidden">Sub-processors no longer engaged<\/caption>[\s\S]*?<\/table>/, '');
    }
    for (const name of retired) {
      if (new RegExp(`\\b${name}\\b`, 'i').test(text)) findings.push(`${f} names ${name}, which the platform lists as no longer engaged`);
    }
  }
  return { retired, findings };
}

const yaml = (s) => JSON.stringify(String(s));

/** Everything this script would write, as { absolutePath: contents }. */
export async function derive() {
  const jiti = loadJiti();
  const help = await jiti.import(path.join(WEB, 'lib', 'help-articles.ts'));
  const brand = await jiti.import(path.join(ASTRO, 'src', 'lib', 'brand-names.ts'));
  const { renderToStaticMarkup } = await jiti.import('react-dom/server');
  const { createElement } = await jiti.import('react');
  const tokens = await jiti.import('@velstrian/tokens');

  const out = {};
  const articles = help.HELP_ARTICLES.map((a) => ({
    slug: a.slug,
    title: a.title,
    summary: a.summary,
    category: a.category,
    product: a.product,
    readingTime: a.readingTime,
    html: siteStyle(dedent(a.content)),
  }));
  const slugs = new Set(articles.map((a) => a.slug));
  if (slugs.size !== articles.length) throw new Error('generate-help-centre: two help articles share a slug');
  const categories = help.HELP_CATEGORIES.map((c) => ({ name: c.name, description: c.description }));
  for (const a of articles) {
    if (!categories.some((c) => c.name === a.category)) {
      throw new Error(`generate-help-centre: article ${a.slug} names category "${a.category}", which HELP_CATEGORIES does not hold`);
    }
  }
  /* Videos: what the page plays, and the files it needs, keyed by output path. */
  const helpVideos = await jiti.import(path.join(WEB, 'src', 'shared', 'help', 'help-videos.ts'));
  const binaries = [];
  const videos = helpVideos.APPROVED_HELP_VIDEOS.map((v) => {
    const mp4 = path.join(VIDEO_SOURCE_DIR, v.src);
    const vtt = path.join(VIDEO_SOURCE_DIR, v.captionsSrc);
    const png = path.join(VIDEO_SOURCE_DIR, v.posterSrc);
    for (const f of [mp4, vtt, png]) {
      if (!fs.existsSync(f)) throw new Error(`generate-help-centre: approved video ${v.id} names ${f}, which is not on disk`);
    }
    const posterName = `${v.id}-poster.webp`;
    binaries.push(
      { kind: 'copy', from: mp4, to: path.join(VIDEO_OUT_DIR, path.basename(v.src)) },
      { kind: 'copy', from: vtt, to: path.join(VIDEO_OUT_DIR, path.basename(v.captionsSrc)) },
      { kind: 'poster', from: png, to: path.join(VIDEO_OUT_DIR, posterName) },
    );
    return {
      id: v.id,
      title: v.title,
      product: v.product,
      audience: v.audience,
      durationSeconds: v.durationSeconds,
      src: `${VIDEO_URL_DIR}${path.basename(v.src)}`,
      captions: `${VIDEO_URL_DIR}${path.basename(v.captionsSrc)}`,
      poster: `${VIDEO_URL_DIR}${posterName}`,
      helpSlug: v.helpSlug ?? null,
      approvedOn: v.approvedOn,
      approvedBy: v.approvedBy,
      sourceSha256: { mp4: sha256(mp4), captions: sha256(vtt), poster: sha256(png) },
    };
  });
  for (const v of videos) {
    if (v.helpSlug && !slugs.has(v.helpSlug)) {
      throw new Error(`generate-help-centre: video ${v.id} links to help article ${v.helpSlug}, which does not exist`);
    }
  }
  derive.binaries = binaries;

  out[HELP_JSON] =
    JSON.stringify(
      {
        _generated: GENERATED_NOTE,
        source: 'crowagent-platform/web/lib/help-articles.ts',
        count: articles.length,
        /* The one support mailbox, SUPPORT_EMAIL in @velstrian/tokens, the same
           address the app route replies from for a support request. */
        supportEmail: tokens.SUPPORT_EMAIL,
        categories,
        videos,
        articles,
      },
      null,
      2,
    ) + '\n';

  for (const route of LEGAL_PAGES) {
    const mod = await jiti.import(path.join(WEB, 'app', '(legal)', route, 'page.tsx'));
    const Page = mod.default;
    const meta = mod.metadata ?? {};
    const titleText = typeof meta.title === 'string' ? meta.title : meta.title?.default;
    if (!titleText || !meta.description) {
      throw new Error(`generate-help-centre: app/(legal)/${route} has no metadata title or description`);
    }
    const { heading, body } = legalMarkdown(renderToStaticMarkup(createElement(Page)), route);
    out[path.join(LEGAL_DIR, `${route}.md`)] =
      [
        '---',
        `title: ${yaml(`${titleText} | ${brand.PLATFORM_SHORT_NAME}`)}`,
        `description: ${yaml(meta.description)}`,
        `heading: ${yaml(`${heading || titleText}.`.replace(/\.\.$/, '.'))}`,
        `eyebrow: ${yaml('Legal and data protection')}`,
        '---',
        `<!-- ${GENERATED_NOTE} Source: crowagent-platform/web/app/(legal)/${route}/page.tsx -->`,
        '',
        body,
        '',
      ].join('\n');
  }
  return out;
}

async function main() {
  const check = process.argv.includes('--check');
  if (!fs.existsSync(path.join(WEB, 'lib', 'help-articles.ts'))) {
    if (check) {
      console.log('check-help-centre: crowagent-platform is not beside this repository, drift check skipped. The committed help centre and legal pages are served as they are.');
      return;
    }
    console.error('generate-help-centre: crowagent-platform/web/lib/help-articles.ts not found. Run this beside the platform checkout.');
    process.exit(1);
  }
  /* Read before anything is written, so a changed source poster is seen as changed. */
  const previous = fs.existsSync(HELP_JSON) ? JSON.parse(fs.readFileSync(HELP_JSON, 'utf8')) : null;
  const files = await derive();
  const drift = [];
  for (const [file, contents] of Object.entries(files)) {
    const rel = path.relative(ASTRO, file);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) {
      if (current !== contents) drift.push(rel);
    } else if (current !== contents) {
      fs.writeFileSync(file, contents);
      console.log(`wrote ${rel}`);
    }
  }
  for (const b of derive.binaries) {
    const rel = path.relative(ASTRO, b.to);
    if (b.kind === 'copy') {
      const same = fs.existsSync(b.to) && sha256(b.to) === sha256(b.from);
      if (check) {
        if (!same) drift.push(rel);
      } else if (!same) {
        fs.mkdirSync(path.dirname(b.to), { recursive: true });
        fs.copyFileSync(b.from, b.to);
        console.log(`copied ${rel}`);
      }
    } else if (check) {
      /* The poster is a re-encode, so its bytes are not the source's. The
         source hash in the JSON is what ties it to the platform, and the JSON
         is compared above, so here it only has to exist. */
      if (!fs.existsSync(b.to)) drift.push(rel);
    } else {
      const known = previous?.videos?.find((v) => b.to.endsWith(path.basename(v.poster)));
      if (!fs.existsSync(b.to) || !known || known.sourceSha256.poster !== sha256(b.from)) {
        const sharp = createRequire(path.join(ASTRO, 'package.json'))('sharp');
        fs.mkdirSync(path.dirname(b.to), { recursive: true });
        await sharp(b.from).resize(960).webp({ quality: 80 }).toFile(b.to);
        console.log(`encoded ${rel}`);
      }
    }
  }
  const { retired, findings } = retiredNameFindings(files);
  if (findings.length) {
    console.error(`check-help-centre: FAIL, a legal page names a sub-processor the platform has retired (${retired.join(', ')}):`);
    for (const f of findings) console.error(`  ${f}`);
    process.exit(1);
  }
  const count = JSON.parse(files[HELP_JSON]).count;
  if (check) {
    if (drift.length) {
      console.error(`check-help-centre: FAIL, ${drift.length} generated file(s) no longer match the platform source:`);
      for (const d of drift) console.error(`  ${d}`);
      console.error('Run `node scripts/generate-help-centre.mjs` from astro/ and commit the result.');
      process.exit(1);
    }
    console.log(`check-help-centre: PASS, ${count} help articles and ${LEGAL_PAGES.length} legal pages match the platform source.`);
    return;
  }
  console.log(`generate-help-centre: ${count} help articles, ${LEGAL_PAGES.length} legal pages.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(JSON.stringify({ level: 'error', service: 'generate-help-centre', error: error instanceof Error ? error.stack : String(error) }));
    process.exit(1);
  });
}
