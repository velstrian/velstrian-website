/**
 * generate-help-centre.mjs: writes the public help centre and the moved legal
 * pages from the platform, so the website never holds a hand copied article.
 *
 * D461 (owner 2026-10-26): the public help centre moves from the app host to
 * velstrian.com/help. D462 (2026-10-26): (1) a path on this site, (3) the
 * public legal pages (DPA, sub-processors, residency, retention, refund) move
 * to the legal collection here, (4) ONE SOURCE: the website copy is GENERATED
 * from crowagent-platform/web/lib/help-articles.ts with the governed figures
 * resolved at build, plus a drift guard. Row R285-WEB-HELP-CENTRE-01, board
 * item A-466.
 *
 * WHY IT IS RUN AND NOT PARSED. help-articles.ts RESOLVES prices, seats,
 * credits, the buyer product name and the PPN 026 and PPN 006 figures from
 * governed modules when it is evaluated. Reading its text with a regex would
 * ship `${PLAN_PRICES_GBP...}` placeholders, and hand copying would freeze a
 * price where the platform's RULE 0-C price guard cannot see it. So the file
 * is evaluated with jiti (the platform's own copy, with the platform tsconfig
 * aliases) and its exported values are written out.
 *
 * The legal pages are React server components. They are rendered to static
 * markup with the platform's own React, class names are dropped (the website
 * styles a legal document from its own tokens, RULE 0-C), headings become
 * Markdown headings so the Legal layout builds its contents rail from them, and
 * every link to a page that stays in the app is written `app:/<path>`, which
 * astro.config.mjs resolves from APP_ORIGIN in src/data/app.ts.
 *
 * OUTPUT, all committed, because Cloudflare Pages has no platform checkout:
 *   src/data/help-centre.generated.json
 *   src/content/legal/{dpa,sub-processors,residency,retention,refund-policy}.md
 *
 * Run from astro/:   node scripts/generate-help-centre.mjs
 * Drift check:       node scripts/generate-help-centre.mjs --check
 * The check fails the build when a committed file differs from what this
 * script would write now. Where crowagent-platform is not beside this
 * repository it says so and passes, the same rule as check-site-facts.mjs.
 */
